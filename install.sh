#!/usr/bin/env bash
# Persona Shell for Zorin OS: one-command installer.
#
# Adds a "Persona Shell (Hyprland)" choice to the login screen, running
# https://github.com/Yujonpradhananga/Persona-Quickshell on top of Hyprland.
# Zorin itself is not changed: pick "Zorin Desktop" at login to go back.
#
#   Install / repair / update:  bash install.sh
#   Remove everything:          persona-shell-uninstall
#
# Hyprland and Quickshell come from Nix (Zorin's own packages are too old for
# this shell), so the first run downloads a few GB and takes 10-30 minutes.

set -euo pipefail

REPO_URL="https://github.com/Yujonpradhananga/Persona-Quickshell"
REPO_COMMIT="6bb02aa50f609be8047f67b8a9984274c91e2060"   # the version these patches were written against

DATA="$HOME/.local/share/persona-shell"
BIN="$HOME/.local/bin"
SESSION_FILE="/usr/share/wayland-sessions/persona-hyprland.desktop"
HYPR_CONF="$HOME/.config/hypr/hyprland.lua"
MARKER="-- Generated by the Persona Shell installer"
NIXF=(--extra-experimental-features "nix-command flakes")

# Graphics variables nixGL sets for Nix programs. Normal Zorin apps must not
# inherit them, or they can crash on start; persona-run strips them again.
GL_VARS="LD_LIBRARY_PATH LIBGL_DRIVERS_PATH LIBVA_DRIVERS_PATH GBM_BACKENDS_PATH __EGL_VENDOR_LIBRARY_FILENAMES VK_ICD_FILENAMES VK_LAYER_PATH QT_PLUGIN_PATH QML_IMPORT_PATH QML2_IMPORT_PATH NIXPKGS_QT6_QML_IMPORT_PATH QT_QPA_PLATFORMTHEME"

# ---------------------------------------------------------------- helpers ----

if [ -t 1 ]; then B=$'\e[1m' G=$'\e[32m' Y=$'\e[33m' R=$'\e[31m' N=$'\e[0m'; else B='' G='' Y='' R='' N=''; fi
step() { printf '\n%s==> %s%s\n' "$B" "$*" "$N"; }
ok()   { printf '  %s✓%s %s\n' "$G" "$N" "$*"; }
warn() { printf '  %s!%s %s\n' "$Y" "$N" "$*"; }
die()  { printf '\n%sSomething went wrong:%s %s\n' "$R" "$N" "$*"; printf 'Send this file to whoever gave you the command: %s\n' "$LOG"; exit 1; }
have_tty() { (exec </dev/tty) 2>/dev/null; }
ask()  { local a=""; have_tty && { read -r -p "  $1 [y/N] " a </dev/tty || true; }; [[ $a == [yY]* ]]; }

mkdir -p "$DATA" "$BIN"
LOG="$DATA/install.log"
: >"$LOG"
exec > >(tee -a "$LOG") 2>&1
trap 'die "the step above failed (line $LINENO)."' ERR

printf '%sPersona Shell installer for Zorin OS%s\n' "$B" "$N"
printf 'This adds a new desktop you can pick at login. Your normal Zorin desktop stays as it is.\n'

# --------------------------------------------------------------- checks ----

step "Checking this computer"

[ "$(id -u)" -ne 0 ] || die "run this as your normal user, not with sudo (it will ask for your password itself)."
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] || die "this needs a 64-bit Intel/AMD PC running Zorin OS."

. /etc/os-release
if [ "${ID:-}" = zorin ] || [ "${ID:-}" = ubuntu ] || [[ " ${ID_LIKE:-} " == *" ubuntu "* ]]; then
    ok "System: ${PRETTY_NAME:-$ID}"
else
    warn "This was made for Zorin OS, but this computer runs ${PRETTY_NAME:-something else}."
    ask "Continue anyway?" || exit 0
fi
case "${VERSION_ID:-}" in
    16*|17*|20.04|22.04) warn "Older Zorin/Ubuntu base: the volume pop-up may not work (it needs PipeWire), everything else should." ;;
esac

avail_gb=$(df --output=avail -BG / | tail -n1 | tr -dc 0-9)
[ "${avail_gb:-0}" -ge 6 ] || die "not enough free disk space: ${avail_gb}GB free, about 6GB needed."
ok "Disk space: ${avail_gb}GB free"

curl -fsI --max-time 15 https://github.com >/dev/null || die "no internet connection (could not reach github.com)."
ok "Internet connection"

GPU_MODE=mesa
gpus=$(lspci 2>/dev/null | grep -Ei 'vga|3d controller|display' || true)
if grep -qi nvidia <<<"$gpus" && [ -r /proc/driver/nvidia/version ]; then
    GPU_MODE=nvidia
    ok "Graphics: NVIDIA with the NVIDIA driver $(grep -oE '[0-9]+\.[0-9]+(\.[0-9]+)?' /proc/driver/nvidia/version | head -n1)"

    # Hyprland needs nvidia-drm modeset, and the login screen (GDM) hides Wayland
    # desktops on NVIDIA unless sleep support is set up the way its udev rule checks.
    nv_issues=()
    [ "$(cat /sys/module/nvidia_drm/parameters/modeset 2>/dev/null)" = Y ] || nv_issues+=("driver mode for Wayland (nvidia-drm modeset) is off")
    if ! grep -q '^EnableS0ixPowerManagement: 1' /proc/driver/nvidia/params 2>/dev/null; then
        grep -q '^PreserveVideoMemoryAllocations: 1' /proc/driver/nvidia/params 2>/dev/null || nv_issues+=("video memory is not kept during sleep")
        for s in suspend resume hibernate; do
            [ "$(systemctl is-enabled "nvidia-$s.service" 2>/dev/null)" = enabled ] || { nv_issues+=("NVIDIA sleep services are off"); break; }
        done
    fi
    # Laptops with Intel/AMD + NVIDIA graphics: GDM always hides Wayland desktops unless its rule is overridden.
    NV_HYBRID=""
    if ls /sys/class/power_supply/BAT* >/dev/null 2>&1 && grep -viq nvidia <<<"$gpus" \
        && grep -qs hybrid_nvidia /usr/lib/udev/rules.d/61-gdm.rules /lib/udev/rules.d/61-gdm.rules \
        && [ ! -e /etc/udev/rules.d/61-gdm.rules ]; then
        NV_HYBRID=1
        nv_issues+=("the login screen hides Wayland desktops on laptops with two graphics chips")
    fi

    if [ ${#nv_issues[@]} -gt 0 ]; then
        warn "Some NVIDIA settings need to change before Persona Shell can start:"
        for i in "${nv_issues[@]}"; do printf '      - %s\n' "$i"; done
        printf '    The installer can change them for you. The computer then needs one restart.\n'
        if ask "Change the NVIDIA settings for you?"; then
            NV_FIX=1
        else
            warn "Without these changes Persona Shell will most likely not start or not show up at login."
            ask "Continue anyway?" || exit 0
        fi
    fi
else
    ok "Graphics: $(sed -E 's/^[^:]*: //' <<<"$gpus" | head -n1)"
fi

printf '  Your password is needed to install system packages and add the login option.\n'
if have_tty; then sudo -v </dev/tty; else sudo -v; fi || die "could not get administrator rights."
( while kill -0 $$ 2>/dev/null; do sudo -n true 2>/dev/null; sleep 50; done ) &   # keep sudo alive during the long download
ok "Administrator rights"

# --------------------------------------------------------- apt packages ----

step "Installing helper programs from Zorin's software sources"
sudo apt-get update -qq || warn "apt update had problems, trying to continue."
sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends \
    git curl xz-utils pciutils fontconfig >/dev/null || die "could not install basic tools (git, curl)."
for p in brightnessctl playerctl pulseaudio-utils libnotify-bin mako-notifier policykit-1-gnome grim slurp wl-clipboard; do
    if sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends "$p" >/dev/null 2>&1; then
        ok "$p"
    else
        warn "$p not available, skipping (only a small feature is lost)."
    fi
done

if [ -n "${NV_FIX:-}" ]; then
    step "Changing the NVIDIA settings"
    sudo tee /etc/modprobe.d/persona-shell-nvidia.conf >/dev/null <<'EOF'
# Added by the Persona Shell installer: needed for Hyprland and Wayland on NVIDIA.
options nvidia-drm modeset=1
options nvidia NVreg_PreserveVideoMemoryAllocations=1
EOF
    ok "Driver options set"
    if [ -f /etc/default/grub ] && ! grep -q 'nvidia-drm.modeset=1' /etc/default/grub; then
        sudo cp /etc/default/grub /etc/default/grub.bak-persona
        sudo sed -i -E '/^GRUB_CMDLINE_LINUX_DEFAULT=/ s/"$/ nvidia-drm.modeset=1"/' /etc/default/grub
        if grep -q 'nvidia-drm.modeset=1' /etc/default/grub && sudo update-grub >/dev/null 2>&1; then
            ok "Boot option added"
        else
            sudo cp /etc/default/grub.bak-persona /etc/default/grub
            warn "Could not add the boot option (the driver option above should be enough)"
        fi
    fi
    for s in suspend resume hibernate; do
        sudo systemctl enable "nvidia-$s.service" >/dev/null 2>&1 || warn "could not enable nvidia-$s"
    done
    ok "NVIDIA sleep services enabled"
    if [ -n "$NV_HYBRID" ]; then
        sudo ln -sf /dev/null /etc/udev/rules.d/61-gdm.rules
        ok "Login screen allowed to show Wayland desktops"
    fi
    sudo update-initramfs -u >/dev/null 2>&1 || warn "update-initramfs had a problem (the restart may still be enough)"
    ok "Done. These take effect after the restart at the end"
    NEED_REBOOT=1
fi

# ------------------------------------------------------------------- nix ----

step "Installing Nix (the package manager that provides Hyprland)"
NIX_PROFILE_SCRIPT=/nix/var/nix/profiles/default/etc/profile.d/nix-daemon.sh
if [ -e "$NIX_PROFILE_SCRIPT" ]; then
    ok "Nix is already installed"
else
    tmp=$(mktemp -d)
    curl -fsSL https://nixos.org/nix/install -o "$tmp/install-nix"
    sh "$tmp/install-nix" --daemon --yes </dev/null || die "the Nix installer failed."
    rm -rf "$tmp"
    ok "Nix installed"
fi
set +u; . "$NIX_PROFILE_SCRIPT"; set -u
command -v nix >/dev/null || die "Nix is installed but the 'nix' command was not found."

step "Downloading Hyprland and Quickshell (the long part: 10-30 minutes)"
mkdir -p "$DATA/flake"
cat >"$DATA/flake/flake.nix" <<'NIX'
{
  description = "Persona Shell for Zorin OS: Hyprland + Quickshell + fonts";

  inputs = {
    nixpkgs.url = "github:NixOS/nixpkgs/nixos-unstable";
    nixgl.url = "github:nix-community/nixGL";
    nixgl.inputs.nixpkgs.follows = "nixpkgs";
  };

  outputs = { self, nixpkgs, nixgl }:
    let
      system = "x86_64-linux";
      pkgs = import nixpkgs { inherit system; overlays = [ nixgl.overlays.default ]; };
      qt = pkgs.qt6;

      # Persona plays videos, so Quickshell also needs QtMultimedia.
      quickshell = pkgs.symlinkJoin {
        name = "quickshell-persona";
        paths = [ pkgs.quickshell ];
        nativeBuildInputs = [ pkgs.makeWrapper ];
        postBuild = ''
          for b in qs quickshell; do
            [ -e "$out/bin/$b" ] || continue
            rm "$out/bin/$b"
            makeWrapper "${pkgs.quickshell}/bin/$b" "$out/bin/$b" \
              --prefix QML_IMPORT_PATH : "${qt.qtmultimedia}/${qt.qtbase.qtQmlPrefix}" \
              --prefix QT_PLUGIN_PATH : "${qt.qtmultimedia}/${qt.qtbase.qtPluginPrefix}"
          done
        '';
      };

      fonts = builtins.filter (p: p != null) [
        (pkgs.montserrat or null)
        (pkgs.material-symbols or null)
        (pkgs.nerd-fonts.jetbrains-mono or null)
        (pkgs.nerd-fonts.symbols-only or null)
        (pkgs.proggyfonts or null)
      ];

      env = extra: pkgs.buildEnv {
        name = "persona-shell";
        paths = [ pkgs.hyprland quickshell pkgs.nixgl.nixGLIntel ] ++ fonts ++ extra;
        ignoreCollisions = true;
      };
    in {
      packages.${system} = {
        default = env [ ];
        # The installer passes the driver version in: nixGL's own detection can't
        # read the version line of NVIDIA's open kernel module (RTX 50 series).
        nvidia = env [ (pkgs.nixgl.nvidiaPackages { version = builtins.getEnv "PERSONA_NVIDIA_VERSION"; }).nixGLNvidia ];
      };
    };
}
NIX
attr=default
if [ "$GPU_MODE" = nvidia ]; then
    attr=nvidia
    PERSONA_NVIDIA_VERSION=$(cat /sys/module/nvidia/version 2>/dev/null || grep -oE '[0-9]+\.[0-9]+(\.[0-9]+)?' /proc/driver/nvidia/version | head -n1)
    export PERSONA_NVIDIA_VERSION
    ok "Using NVIDIA driver files for version $PERSONA_NVIDIA_VERSION"
fi
build=(nix "${NIXF[@]}" build --impure --out-link "$DATA/env" "path:$DATA/flake#$attr")
if have_tty; then
    # Straight to the screen so the progress bar shows; on failure, run again into the log to keep the error.
    if ! "${build[@]}" 2>/dev/tty; then
        printf '\nRetrying once and saving the error to the log...\n'
        "${build[@]}" -L 2>&1 | tail -n 80 || true
        "${build[@]}" >/dev/null 2>&1 || die "downloading Hyprland/Quickshell failed."
    fi
else
    "${build[@]}" -L || die "downloading Hyprland/Quickshell failed."
fi
ENV="$DATA/env"
ok "Hyprland $("$ENV/bin/Hyprland" --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n1 || echo '?') ready"

step "Installing fonts"
mkdir -p "$HOME/.local/share/fonts/persona-shell"
if [ -d "$ENV/share/fonts" ]; then
    cp -rL --no-preserve=mode "$ENV/share/fonts/." "$HOME/.local/share/fonts/persona-shell/"
fi
fc-cache -f >/dev/null 2>&1 || true
ok "Fonts installed"

# ----------------------------------------------------------------- shell ----

step "Downloading Persona Shell"
REPO="$DATA/repo"
if [ ! -d "$REPO/.git" ]; then
    rm -rf "$REPO"
    git init -q "$REPO"
    git -C "$REPO" remote add origin "$REPO_URL"
fi
git -C "$REPO" fetch -q --depth 1 origin "$REPO_COMMIT" || die "could not download Persona Shell from GitHub."
git -C "$REPO" reset -q --hard FETCH_HEAD
git -C "$REPO" clean -qfd
ok "Persona Shell downloaded"

# Patch 1: drop the Cava visualizer (it needs a plugin compiled by hand, see the repo README).
we="$REPO/Widgets/WallpaperEngine.qml"
awk '
    /^[[:space:]]*CavaVisualizer[[:space:]]*\{/ && !done { skip = 1; depth = 0 }
    skip { depth += gsub(/\{/, "{") - gsub(/\}/, "}"); if (depth <= 0) { skip = 0; done = 1 }; next }
    { print }
' "$we" >"$we.new" && mv "$we.new" "$we"
rm -f "$REPO/Widgets/CavaVisualizer.qml"
grep -q CavaVisualizer "$we" && warn "could not remove the Cava visualizer" || ok "Removed the Cava visualizer (needs a hand-built plugin)"

# Patch 2: start apps from the launcher through persona-run, so they get a clean environment.
sa="$REPO/Layers/Searchapp.qml"
awk '
    { print }
    /property bool forcedOpen: false/ && !done {
        print ""
        print "    // Added by the Persona Shell installer: start apps without the Nix graphics paths."
        print "    function personaLaunch(entry) {"
        print "        const cmd = [Quickshell.env(\"HOME\") + \"/.local/bin/persona-run\"];"
        print "        if (entry.runInTerminal)"
        print "            cmd.push(\"gnome-terminal\", \"--\");"
        print "        Quickshell.execDetached({"
        print "            command: cmd.concat(Array.prototype.slice.call(entry.command)),"
        print "            workingDirectory: entry.workingDirectory || Quickshell.env(\"HOME\")"
        print "        });"
        print "    }"
        done = 1
    }
' "$sa" >"$sa.new" && mv "$sa.new" "$sa"
sed -i -e 's/filteredApps\[appList\.currentIndex\]\.execute();/root.personaLaunch(filteredApps[appList.currentIndex]);/' \
       -e 's/delegateRoot\.modelData\.execute();/root.personaLaunch(delegateRoot.modelData);/' "$sa"
if grep -q '\.execute();' "$sa" || ! grep -q personaLaunch "$sa"; then
    warn "could not patch the app launcher; some apps may not open from it"
else
    ok "Patched the app launcher"
fi

# Patch 3: two fonts the Options menu loads from the repo but which are not included in it.
mkdir -p "$REPO/Assets/fonts"
curl -fsSL -o "$REPO/Assets/fonts/BebasNeue-Regular.ttf" https://github.com/google/fonts/raw/main/ofl/bebasneue/BebasNeue-Regular.ttf \
    && curl -fsSL -o "$REPO/Assets/fonts/Montserrat-Light.ttf" https://github.com/JulietaUla/Montserrat/raw/master/fonts/ttf/Montserrat-Light.ttf \
    && ok "Added missing menu fonts" || warn "could not download two menu fonts (text will use a fallback font)"

mkdir -p "$HOME/.config/quickshell"
if [ -e "$HOME/.config/quickshell/persona" ] && [ ! -L "$HOME/.config/quickshell/persona" ]; then
    mv "$HOME/.config/quickshell/persona" "$HOME/.config/quickshell/persona.bak-$(date +%s)"
fi
ln -sfn "$REPO" "$HOME/.config/quickshell/persona"

# ------------------------------------------------------- helper scripts ----

step "Writing helper scripts"

cat >"$BIN/persona-run" <<EOF
#!/bin/sh
# Starts a normal Zorin app from inside the Persona/Hyprland session, putting back
# the environment the login screen gave us (Nix graphics paths would crash it).
for v in $GL_VARS; do
    if eval "[ -n \"\\\${PERSONA_ORIG_\$v+x}\" ]"; then
        eval "export \$v=\"\\\$PERSONA_ORIG_\$v\""
    else
        unset "\$v"
    fi
done
exec "\$@"
EOF

cat >"$BIN/persona-hyprland" <<EOF
#!/bin/sh
# Login-screen entry point for the "Persona Shell (Hyprland)" session.
[ -r $NIX_PROFILE_SCRIPT ] && . $NIX_PROFILE_SCRIPT
PS_ENV="$ENV"
export PATH="\$HOME/.local/bin:\$PS_ENV/bin:\$PATH"
export XDG_CURRENT_DESKTOP=Hyprland XDG_SESSION_DESKTOP=Hyprland XDG_SESSION_TYPE=wayland

# Remember the original environment so persona-run can restore it for normal apps.
for v in $GL_VARS; do
    if eval "[ -n \"\\\${\$v+x}\" ]"; then eval "export PERSONA_ORIG_\$v=\"\\\$\$v\""; fi
done

# Nix wrappers prepend to XDG_DATA_DIRS; if it starts empty, the system app list would vanish.
export XDG_DATA_DIRS="\${XDG_DATA_DIRS:-/usr/local/share:/usr/share:/var/lib/flatpak/exports/share:\$HOME/.local/share/flatpak/exports/share:/var/lib/snapd/desktop}"

exec >"\$HOME/.local/share/persona-shell/session.log" 2>&1
# start-hyprland is Hyprland's crash-restarting launcher. It looks for a "nixGL"
# command itself, so tell it we already wrap it (--no-nixgl).
set -- "\$PS_ENV/bin/Hyprland"
[ -x "\$PS_ENV/bin/start-hyprland" ] && set -- "\$PS_ENV/bin/start-hyprland" --no-nixgl
nv=\$(ls "\$PS_ENV"/bin/nixGLNvidia-* 2>/dev/null | head -n1)
if [ -n "\$nv" ]; then
    exec "\$nv" "\$PS_ENV/bin/nixGLIntel" "\$@"
else
    exec "\$PS_ENV/bin/nixGLIntel" "\$@"
fi
EOF

cat >"$BIN/persona-shell-update" <<EOF
#!/bin/sh
# Updates Hyprland, Quickshell and fonts. Run it from normal Zorin, e.g. after an NVIDIA driver update.
set -e
. $NIX_PROFILE_SCRIPT
PERSONA_NVIDIA_VERSION=\$(cat /sys/module/nvidia/version 2>/dev/null || true)
export PERSONA_NVIDIA_VERSION
nix --extra-experimental-features "nix-command flakes" flake update --flake "path:$DATA/flake"
nix --extra-experimental-features "nix-command flakes" build --impure --out-link "$DATA/env" "path:$DATA/flake#$attr"
cp -rL --no-preserve=mode "$DATA/env/share/fonts/." "\$HOME/.local/share/fonts/persona-shell/" 2>/dev/null || true
fc-cache -f >/dev/null 2>&1 || true
echo "Persona Shell is up to date. Log out and back in to use the new version."
EOF

cat >"$BIN/persona-shell-uninstall" <<EOF
#!/bin/sh
# Removes Persona Shell and the login option. Nix itself stays installed.
echo "Removing Persona Shell..."
sudo rm -f "$SESSION_FILE"
rm -f "\$HOME/.config/quickshell/persona"
if grep -qF -- "$MARKER" "$HYPR_CONF" 2>/dev/null; then rm -f "$HYPR_CONF"; fi
rm -rf "$DATA" "\$HOME/.local/share/fonts/persona-shell"
rm -f "\$(xdg-user-dir DESKTOP 2>/dev/null || echo "\$HOME/Desktop")/Persona Shell - keys.txt"
fc-cache -f >/dev/null 2>&1 || true
rm -f "$BIN/persona-run" "$BIN/persona-hyprland" "$BIN/persona-shell-update"
# The NVIDIA settings are standard and harmless, so they are kept; only the
# login-screen override for two-GPU laptops is undone.
if [ "\$(readlink /etc/udev/rules.d/61-gdm.rules 2>/dev/null)" = /dev/null ]; then
    sudo rm -f /etc/udev/rules.d/61-gdm.rules
fi
if [ -r $NIX_PROFILE_SCRIPT ]; then
    . $NIX_PROFILE_SCRIPT
    echo "Freeing disk space..."
    nix-collect-garbage >/dev/null 2>&1 || true
fi
rm -f "\$0"
echo "Done. Persona Shell is gone; log in with 'Zorin Desktop' as usual."
EOF
chmod +x "$BIN/persona-run" "$BIN/persona-hyprland" "$BIN/persona-shell-update" "$BIN/persona-shell-uninstall"
ok "persona-run, persona-hyprland, persona-shell-update, persona-shell-uninstall"

# ------------------------------------------------------ hyprland config ----

step "Writing the Hyprland settings"

# Copy keyboard layout and touchpad scrolling from his Zorin settings.
kb=$(gsettings get org.gnome.desktop.input-sources sources 2>/dev/null | grep -oE "'xkb', '[^']+'" | head -n1 | sed -E "s/.*, '//; s/'$//" || true)
[ -n "$kb" ] || kb=$(localectl status 2>/dev/null | sed -n 's/.*X11 Layout: *//p' | cut -d, -f1)
KB_LAYOUT=${kb%%+*}; KB_LAYOUT=${KB_LAYOUT:-us}
KB_VARIANT=""; [[ $kb == *+* ]] && KB_VARIANT=${kb#*+}
NATURAL=$(gsettings get org.gnome.desktop.peripherals.touchpad natural-scroll 2>/dev/null || echo true)
[ "$NATURAL" = true ] || NATURAL=false
ok "Keyboard layout: $KB_LAYOUT${KB_VARIANT:+ ($KB_VARIANT)}"

write_config() {   # $1 = full | safe
    mkdir -p "$(dirname "$HYPR_CONF")"
    {
        cat <<'LUA'
-- Generated by the Persona Shell installer
-- Hyprland settings for the "Persona Shell (Hyprland)" session.
-- Wiki: https://wiki.hypr.land/configuring/

hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "auto" })

local run      = "persona-run "       -- starts normal Zorin apps with a clean environment
local terminal = run .. "gnome-terminal"
local files    = run .. "nautilus --new-window"
local launcher = "qs -c persona ipc call searchapp toggle"

hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP XDG_SESSION_TYPE HYPRLAND_INSTANCE_SIGNATURE")
    hl.exec_cmd("qs -c persona")
    hl.exec_cmd(run .. "mako")
    hl.exec_cmd("[ -x /usr/lib/policykit-1-gnome/polkit-gnome-authentication-agent-1 ] && " .. run .. "/usr/lib/policykit-1-gnome/polkit-gnome-authentication-agent-1")
    hl.exec_cmd("sleep 4; " .. run .. "notify-send -t 15000 'Persona Shell' 'Super+Space: apps   Super+Enter: terminal   Super+E: files   Alt+F4: close   Super+Shift+E: log out'")
end)

hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_SIZE", "24")

hl.config({
    input = {
        kb_layout  = "@KB_LAYOUT@",
        kb_variant = "@KB_VARIANT@",
        follow_mouse = 1,
        touchpad = { natural_scroll = @NATURAL@ },
    },
    misc = {
        force_default_wallpaper = 0,
        disable_hyprland_logo   = true,
    },
})

local mainMod = "SUPER"

hl.bind(mainMod .. " + space",       hl.dsp.exec_cmd(launcher))
hl.bind(mainMod .. " + R",           hl.dsp.exec_cmd(launcher))
hl.bind(mainMod .. " + Return",      hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + E",           hl.dsp.exec_cmd(files))
hl.bind("ALT + F4",                  hl.dsp.window.close())
hl.bind(mainMod .. " + Q",           hl.dsp.window.close())
hl.bind(mainMod .. " + SHIFT + E",   hl.dsp.exec_cmd("hyprctl dispatch 'hl.dsp.exit()'"))
LUA
        if [ "$1" = full ]; then
            cat <<'LUA'

hl.config({
    general = {
        gaps_in  = 5,
        gaps_out = 14,
        border_size = 2,
        col = {
            active_border   = { colors = {"rgba(1a6affee)", "rgba(7dd4fcee)"}, angle = 45 },
            inactive_border = "rgba(0d1a3aaa)",
        },
        layout = "dwindle",
    },
